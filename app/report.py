import logging
import os
from collections.abc import Sequence

from app.schemas import Report, SectionResult

logger = logging.getLogger(__name__)

EMPTY_CONTENT = "Not enough verified information found."
EMPTY_ISSUE = "No usable sources were found for this question."

# Source quality classifications
SOURCE_QUALITY_LABELS = {
    "official": "official",
    "academic": "academic",
    "news": "news",
    "company": "company",
    "aggregator": "aggregator",
    "unknown": "unknown",
}

# Official domains: .gov.pk, .gov, .int, .org.pk government-style bodies
OFFICIAL_DOMAINS = {
    ".gov.pk",
    ".gov",
    ".int",
    ".org.pk",
}

# Academic domains
ACADEMIC_DOMAINS = {
    ".edu",
    ".ac",
    "sciencedirect.com",
    "springer.com",
    "mdpi.com",
    "researchgate.net",
    "academia.edu",
}

# News domains
NEWS_DOMAINS = {
    "brecorder.com",
    "dawn.com",
    "tribune.com.pk",
    "thenews.com.pk",
    "reuters.com",
    "bbc.com",
}

# Aggregator domains
AGGREGATOR_DOMAINS = {
    "marketresearchreports.com",
    "market.us",
    "marketsandmarkets.com",
    "maximizemarketresearch.com",
    "stellarmr.com",
    "6wresearch.com",
    "marketdataforecast.com",
    "statista.com",
}


def classify_source(url: str) -> str:
    """Classify a source URL into one of: official, academic, news, company, aggregator, unknown."""
    from urllib.parse import urlparse

    parsed = urlparse(url)
    if not parsed.netloc:
        return "unknown"

    netloc = parsed.netloc.lower()
    # Remove port number if present
    if ":" in netloc:
        netloc = netloc.split(":")[0]
    # Strip trailing dots
    while netloc.endswith("."):
        netloc = netloc[:-1]
    # Remove www. prefix
    if netloc.startswith("www."):
        netloc = netloc[4:]

    # Check aggregator domains first (specific)
    if netloc in AGGREGATOR_DOMAINS:
        return "aggregator"

    # Check academic domains
    for domain in ACADEMIC_DOMAINS:
        if netloc == domain or netloc.endswith("." + domain):
            return "academic"

    # Check news domains
    for domain in NEWS_DOMAINS:
        if netloc == domain or netloc.endswith("." + domain):
            return "news"

    # Check official domains: .gov.pk, .gov, .int, .org.pk
    for domain in OFFICIAL_DOMAINS:
        if netloc == domain or netloc.endswith("." + domain):
            return "official"

    # Check company: any .com.pk or .com not in above lists
    if netloc.endswith(".com.pk") or netloc.endswith(".com"):
        return "company"

    return "unknown"


def get_source_label(url: str) -> str:
    """Get the quality label for a source URL."""
    return SOURCE_QUALITY_LABELS.get(classify_source(url), "unknown")


def build_markdown(report: Report, include_empty: bool) -> str:
    """Build Markdown for a report, optionally omitting sections with no evidence."""
    sections = sort_sections(report.sections)
    if not include_empty:
        sections = [section for section in sections if section_group(section) != 2]
    if not sections and not report.editor_summary:
        return ""

    # Global source numbering across all sections
    source_urls = list(dict.fromkeys(
        url for section in sections for url in section.sources
    ))
    source_numbers = {url: index for index, url in enumerate(source_urls, 1)}

    lines = [
        f"# {report.topic}",
        "",
        "> Generated by Dossier AI agents; verify sources",
        "",
    ]
    if report.editor_summary:
        lines.extend(["## Executive Summary", "", report.editor_summary, ""])

    for index, section in enumerate(sections, 1):
        group = section_group(section)
        lines.extend([f"## Section {index}: {section.draft.title}", ""])

        # Badge logic
        if group == 2:
            # Empty section: gray "No evidence found" badge
            lines.extend([f"> **No evidence found**", ""])
        elif group == 1:
            # Section with text but failed review: orange "Unverified" badge
            notes = "; ".join(
                f"{issue.claim}: {issue.problem}".strip(": ")
                for issue in section.issues
            ) or "No review notes recorded."
            lines.extend([f"> **Unverified.** Review notes: {notes}", ""])
        else:
            # Section passed review: green "Passed review" badge
            lines.extend([f"> **Passed review**", ""])

        if section.source_check_summary:
            lines.extend(
                [f"> **Source check:** {section.source_check_summary}", ""]
            )

        # Section notes: "Single source" if exactly one source URL
        unique_urls = list(dict.fromkeys(section.sources))
        if len(unique_urls) == 1:
            lines.append("*Single source*")

        # "Low-reliability sources" note: every source is aggregator or company
        quality_labels = [get_source_label(url) for url in unique_urls]
        if all(q in ("aggregator", "company") for q in quality_labels):
            lines.append("*Low-reliability sources*")

        # Inline citations [n] using GLOBAL source numbering
        citations = " ".join(
            f"[{source_numbers[url]}]"
            for url in dict.fromkeys(section.sources)
            if url in source_numbers
        )
        content = section.draft.content.rstrip()
        if citations:
            content = f"{content} {citations}"
        lines.extend([content, ""])

    lines.extend(["## Sources", ""])
    if source_urls:
        lines.extend(
            f"{index}. {url} ({get_source_label(url)})" for index, url in enumerate(source_urls, 1)
        )
    else:
        lines.append("No sources.")

    return "\n".join(lines) + "\n"


def section_group(section: SectionResult) -> int:
    """Return the report-ordering group for a section."""
    is_empty = (
        section.draft.content.strip() == EMPTY_CONTENT
        or not section.sources
        or any(issue.problem == "no facts retrieved" for issue in section.issues)
    )
    if is_empty:
        return 2
    return 0 if section.passed else 1


def sort_sections(sections: Sequence[SectionResult]) -> list[SectionResult]:
    """Sort sections by review/evidence group, preserving order within each group."""
    return sorted(sections, key=section_group)


def save_report(report: Report, output_dir: str = "reports") -> str:
    """Write a pipeline Report as Markdown and return its path."""
    os.makedirs(output_dir, exist_ok=True)
    markdown = build_markdown(report, include_empty=True)
    filepath = os.path.join(output_dir, f"{_slugify(report.topic)}.md")

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(markdown)

    logger.info("Generated Markdown report: %s", filepath)
    return filepath


def _slugify(topic: str) -> str:
    """Convert a topic string to a filesystem-safe slug."""
    slug = "".join(
        character if character.isalnum() or character in "-_ " else ""
        for character in topic.strip()
    ).lower()
    return "-".join(slug.split())


